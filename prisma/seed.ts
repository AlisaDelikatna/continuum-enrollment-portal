async function main() {
  console.log("Clearing existing demo data…");
  await prisma.outboxEmail.deleteMany();
  await prisma.document.deleteMany();
  await prisma.statusEvent.deleteMany();
  await prisma.enrollment.deleteMany();
  await prisma.user.deleteMany();

  await rm(UPLOAD_DIR, { recursive: true, force: true });
  await mkdir(UPLOAD_DIR, { recursive: true });

  const admin = await prisma.user.create({
    data: { ...ADMIN, role: "ADMIN", createdAt: daysAgo(400) },
  });

  const reps = [];
  for (const rep of REPS) {
    reps.push(
      await prisma.user.create({
        data: { ...rep, role: "REP", createdAt: daysAgo(380) },
      }),
    );
  }

  const counters: Record<string, number> = { EMPLOYEE: 0, VENDOR: 0, PARTICIPANT: 0 };
  let documentTotal = 0;
  let todayTotal = 0;

  for (const seed of ENROLLMENTS) {
    counters[seed.type] += 1;
    const refId = `CFS-${TYPE_PREFIX[seed.type]}-${String(counters[seed.type]).padStart(4, "0")}`;
    const createdAt = daysAgo(seed.age, 9, 15);
    const rep = seed.repIndex !== undefined ? reps[seed.repIndex] : null;

    const enrollee = await prisma.user.create({
      data: {
        name: seed.name,
        email: seed.email,
        phone: seed.phone,
        role: "ENROLLEE",
        createdAt,
      },
    });

    const enrollment = await prisma.enrollment.create({
      data: {
        refId,
        type: seed.type,
        programs: { create: seed.programs.map((program) => ({ program })) },
        status: seed.status,
        name: seed.name,
        email: seed.email,
        phone: seed.phone,
        participantName: seed.participantName ?? null,
        repNameRaw: seed.repNameRaw ?? rep?.name ?? null,
        repEmailRaw: seed.repEmailRaw ?? rep?.email ?? null,
        businessName: seed.businessName ?? null,
        contactName: seed.contactName ?? null,
        enrolleeId: enrollee.id,
        repId: rep?.id ?? null,
        createdAt,
        updatedAt: createdAt,
      },
    });

    // --- status history ------------------------------------------------
    const chain = chainFor(seed.status, Boolean(seed.detour));
    const spanMs = Math.max(NOW.getTime() - createdAt.getTime(), 36 * 3600 * 1000);
    const stepMs = spanMs / (chain.length + 1);

    for (let index = 0; index < chain.length; index++) {
      const status = chain[index];
      const at = new Date(createdAt.getTime() + stepMs * index);
      const isLatestMissing =
        status === "MISSING_INFO" && index === chain.length - 1 && seed.missingNote;
      await prisma.statusEvent.create({
        data: {
          enrollmentId: enrollment.id,
          status,
          note: isLatestMissing
            ? seed.missingNote
            : status === "MISSING_INFO"
              ? "Items requested from the enrollee; enrollment placed on hold."
              : STATUS_NOTES[status],
          changedById: index === 0 ? enrollee.id : admin.id,
          createdAt: at,
        },
      });
    }

    const lastEventAt = new Date(createdAt.getTime() + stepMs * (chain.length - 1));

    // --- documents -----------------------------------------------------
    const required = documentsFor(seed.type);
    const howMany = documentCountFor(seed.status, required.filter((d) => d.required).length);
    const requiredDocs = required.filter((d) => d.required).slice(0, howMany);
    const optionalDoc =
      seed.status === "ACTIVE" || seed.status === "PROCESSED"
        ? required.find((d) => !d.required)
        : undefined;
    const toUpload = optionalDoc ? [...requiredDocs, optionalDoc] : requiredDocs;

    let uploadsTodayLeft = seed.uploadsToday ?? 0;

    for (let index = 0; index < toUpload.length; index++) {
      const doc = toUpload[index];
      const file = await writePlaceholder(seed.businessName ?? seed.name, doc.label);

      let uploadedAt: Date;
      if (uploadsTodayLeft > 0 && index === toUpload.length - 1) {
        uploadedAt = todayAt(8 + todayTotal, 5 + todayTotal * 7);
        uploadsTodayLeft -= 1;
        todayTotal += 1;
      } else {
        const window = Math.max(lastEventAt.getTime() - createdAt.getTime(), 3600 * 1000);
        uploadedAt = new Date(
          createdAt.getTime() + (window * (index + 1)) / (toUpload.length + 1),
        );
      }

      // Reps file roughly every third employee document; admins key in faxes.
      const uploader =
        seed.type === "EMPLOYEE" && rep && index % 3 === 2
          ? rep
          : index === 0 && seed.status === "ACTIVE"
            ? admin
            : enrollee;

      await prisma.document.create({
        data: {
          enrollmentId: enrollment.id,
          docKey: doc.key,
          label: doc.label,
          originalName: file.originalName,
          storedName: file.storedName,
          mimeType: file.mimeType,
          size: file.size,
          uploadedById: uploader.id,
          createdAt: uploadedAt,
        },
      });
      documentTotal += 1;
    }

    // --- outbox: confirmation + the latest status notification ---------
    const received = await sendEnrollmentReceivedEmail(enrollment.id);
    if (received) {
      await prisma.outboxEmail.update({
        where: { id: received.id },
        data: { createdAt },
      });
    }

    const latest = chain[chain.length - 1];
    if (latest !== "RECEIVED") {
      const note =
        latest === "MISSING_INFO" && seed.missingNote
          ? seed.missingNote
          : STATUS_NOTES[latest];
      const email = await sendStatusChangeEmail({
        enrollmentId: enrollment.id,
        status: latest,
        note,
        changedByName: admin.name,
      });
      if (email) {
        await prisma.outboxEmail.update({
          where: { id: email.id },
          data: { createdAt: lastEventAt },
        });
      }
    }
  }

  // Yesterday's digest, so the outbox shows what one looks like before the
  // demo presses the button.
  const yesterday = daysAgo(1, 18, 0);
  const { email: digestEmail } = await sendDailyDigest(yesterday);
  if (digestEmail) {
    await prisma.outboxEmail.update({
      where: { id: digestEmail.id },
      data: { createdAt: daysAgo(0, 7, 0) },
    });
  }

  const [users, enrollments, documents, emails] = await Promise.all([
    prisma.user.count(),
    prisma.enrollment.count(),
    prisma.document.count(),
    prisma.outboxEmail.count(),
  ]);

  console.log("");
  console.log("Seed complete:");
  console.log(`  users        ${users} (1 admin, ${REPS.length} reps, ${enrollments} enrollees)`);
  console.log(`  enrollments  ${enrollments}`);
  console.log(`  documents    ${documents} placeholder PDFs in ./uploads (${todayTotal} dated today)`);
  console.log(`  outbox       ${emails} messages`);
  console.log("");
  console.log(`  Admin login:  ${ADMIN.name} — pick them in the header switcher`);
  console.log(`  Reps:         ${REPS.map((r) => r.name).join(", ")}`);
  console.log("");
  void documentTotal;
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
