function placeholderPdf(title: string, lines: string[]) {
  const esc = (s: string) =>
    s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");

  const stream = [
    `BT /F1 16 Tf 72 720 Td (${esc(title)}) Tj ET`,
    ...lines.map((line, i) => `BT /F1 11 Tf 72 ${688 - i * 18} Td (${esc(line)}) Tj ET`),
  ].join("\n");

  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
    `<< /Length ${Buffer.byteLength(stream, "latin1")} >>\nstream\n${stream}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];

  let out = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(out, "latin1"));
    out += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xref = Buffer.byteLength(out, "latin1");
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) out += `${String(offset).padStart(10, "0")} 00000 n \n`;
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;

  return Buffer.from(out, "latin1");
}

const slug = (value: string) =>
  value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function writePlaceholder(enrolleeName: string, docLabel: string) {
  const originalName = `${slug(enrolleeName)}-${slug(docLabel)}.pdf`;
  const storedName = `${randomUUID()}__${originalName}`;
  const bytes = placeholderPdf(docLabel, [
    `Enrollee: ${enrolleeName}`,
    "Continuum Fiscal Services — sample document",
    "",
    "This is placeholder content generated by the demo seed script.",
    "It contains no real personal or health information.",
  ]);
  await writeFile(path.join(UPLOAD_DIR, storedName), bytes);
  return { originalName, storedName, size: bytes.byteLength, mimeType: "application/pdf" };
}

